-- ── A guessed city no longer invents a shared city ──────────────────────────
-- The rule that was worth making when 1,180 cities were guesses is worth far more
-- now that it applies to 85. Two people are "same city" only when both schools'
-- cities are actually known. Otherwise they fall through to degree 5/6 — same
-- country — which is always true of them. Under-reporting is recoverable; a false
-- connection gets acted on.
create or replace function public.pair_degree(
  a_school bigint, a_city text, a_region text, a_country text, a_start date, a_end date,
  b_school bigint, b_city text, b_region text, b_country text, b_start date, b_end date
) returns table (degree smallint, context_type text, context_label text, same_time boolean)
language sql immutable parallel safe as $$
  with t as (
    select public.ranges_overlap(a_start, a_end, b_start, b_end) as same,
           (a_city is not null and a_city = b_city and a_country = b_country
            and (a_region is null or b_region is null or a_region = b_region)) as same_city
  )
  select
    case
      when a_school = b_school then (case when t.same then 1 else 2 end)
      when t.same_city         then (case when t.same then 3 else 4 end)
      when a_country = b_country then (case when t.same then 5 else 6 end)
    end::smallint,
    case
      when a_school = b_school   then 'school'
      when t.same_city           then 'city'
      when a_country = b_country then 'country'
    end,
    case
      when a_school = b_school then (select name from public.schools where id = a_school)
      when t.same_city then a_city
                            || coalesce(', ' || coalesce(a_region, b_region), '')
                            || ', ' || a_country
      when a_country = b_country then a_country
    end,
    t.same
  from t
  where a_country = b_country;
$$;

