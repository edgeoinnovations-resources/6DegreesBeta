-- ============================================================================
-- Real cities for the school catalogue, from Paul's geocoding pass.
--
-- Until now 1,180 of 2,120 schools (56%) had no stated city. The ISR list never
-- gave one, so where it could not be read out of the school's own name the
-- importer used the country's largest city and recorded that honestly as
-- city_source = 'fallback-largest-city'. It put 87 schools in Shanghai, 73 in
-- Dubai, 9 of Honduras's 11 in Tegucigalpa, and Linda and Robb's American School
-- of Kuwait in Al Aḩmadī. Because the degree engine matches on city name, every
-- one of those clusters was a machine for inventing degree-3 connections between
-- people who were never in the same place: 16,427 false school pairs in the top
-- 14 countries alone.
--
-- Paul geocoded the whole list by hand and graded every row High, Medium or Low.
--
-- WHAT WAS CHECKED BEFORE TRUSTING IT (18 Sep 2026):
--   * Nine schools whose city we already knew independently — Dave's Escuela
--     Internacional de Sampedrana, the members' own postings — all matched.
--   * A stratified sample verified against school websites and directories:
--     High 12/12 correct, Medium 3/3, Low 0/2. The two failures (Kuwait Bilingual
--     School, actually Al-Jahra; Global Bilingual Academy, actually Mahboula) were
--     both graded Low by the file itself.
--   * It gets hard cases right that a naive geocoder does not: American School of
--     The Hague is in Wassenaar, British School of Brussels in Tervuren, Shekou
--     International in Shenzhen, Lucaya International in Freeport.
--   * So High and Medium are trusted; Low is recorded but marked uncertain.
--
-- MATCHING. 2,115 of 2,133 CSV rows joined to a school on normalised name plus
-- country, with no ambiguity. The 18 that did not are name variants (the Maple
-- Leaf group, two Congos) and keep what they have. The country labels needed
-- aliasing because this database was normalised earlier and the CSV keeps ISR's
-- spellings: Korea/South Korea, Great Britain/United Kingdom, Kurdistan/Iraq.
--
-- ACCENTS ARE NOT OVERWRITTEN. The CSV strips diacritics, so 66 rows would have
-- turned Brasília into Brasilia and São Paulo into Sao Paulo. Where the two names
-- differ only by accent the existing spelling is kept.
--
-- COORDINATES FOLLOW THE CITY. A school whose city changes must not keep the old
-- city's pin, or the map moves people to places they never worked.
--
-- KNOWN IMPERFECTION, recorded rather than hidden: Beijing International Bilingual
-- Academy has campuses in Beijing, Tianjin and Guiyang and the file picks Guiyang;
-- its main campus is Beijing. Nobody has a posting there. A member who worked at
-- one of these can correct it — which is the durable fix for the remaining 85.
-- ============================================================================

